#!/usr/bin/env python3
"""parse-review-results.py — Parse ego-review .review.md into structured JSON.

Usage: parse-review-results.py REVIEW_MD [OPTIONS]

Reads a .review.md file (generated by ego-review during field tests),
extracts structured findings, and outputs JSON to stdout.

Options:
  --name NAME           Extension name (default: derived from report header)
  --annotations YAML    Annotation file for unclassified finding filtering
"""

import json
import os
import re
import sys
from datetime import datetime, timezone


# --- Category inference from title keywords ---

CATEGORY_KEYWORDS = [
    (['signal', 'disconnect', 'destroy', 'enable', 'disable', 'leak',
      'cleanup', 'dispose', 'remove_child', 'messagetray'], 'lifecycle'),
    (['spawn', 'dconf', 'pkexec', 'telemetry', 'injection', 'xss'], 'security'),
    (['css', 'selector', 'scoping', 'stylesheet', 'theme class'], 'css'),
    (['async', 'await', '_destroyed', 'cancellable', 'promise'], 'async'),
    (['deprecated', 'removed api', 'dead code', 'removed before'], 'deprecated'),
    (['gobject', 'gtypename', 'registerclass'], 'gobject'),
    (['constructor', 'init-time', 'module-scope', 'module.scope',
      'mutable state'], 'init'),
    (['accessible', 'a11y', 'screen.reader'], 'accessibility'),
    (['import', 'gtk', 'prefs'], 'imports'),
    (['schema', 'gsettings', 'dconf'], 'schema'),
]


def infer_category(title):
    """Infer finding category from title keywords."""
    lower = title.lower()
    for keywords, category in CATEGORY_KEYWORDS:
        if any(kw in lower for kw in keywords):
            return category
    return 'quality'


def make_review_finding_id(title, category):
    """Create a stable finding ID for a review finding.

    Uses review/ prefix to distinguish from ego-lint findings in annotations.
    """
    stable = re.sub(r'`[^`]*`', '', title)
    stable = re.sub(r'\([\w\s/,-]+\)\s*$', '', stable)
    stable = re.sub(r':\d+[-–]\d+', '', stable)
    stable = re.sub(r':\d+', '', stable)
    stable = ' '.join(stable.split()).strip()
    if not stable:
        stable = 'unnamed'
    return f"review/{category}::{stable}"


# --- Annotation parser (adapted from diff-baselines.py) ---

def parse_annotations(path):
    """Parse annotation YAML into a dict of finding_id -> classification."""
    annotations = {}
    if not path or not os.path.isfile(path):
        return annotations

    current_id = None
    with open(path) as f:
        for raw_line in f:
            stripped = raw_line.strip()
            if not stripped or stripped.startswith('#'):
                continue

            if stripped.startswith('- '):
                rest = stripped[2:].strip()
                if rest.startswith('id:'):
                    if current_id is not None and current_id not in annotations:
                        print(f"Warning: annotation '{current_id}' has no classification",
                              file=sys.stderr)
                    val = rest[3:].strip().strip('"').strip("'")
                    current_id = val
                continue

            if ':' in stripped:
                k, v = stripped.split(':', 1)
                k = k.strip()
                v = v.strip().strip('"').strip("'")
                if current_id is None:
                    continue
                if k == 'id':
                    if current_id not in annotations:
                        print(f"Warning: annotation '{current_id}' has no classification",
                              file=sys.stderr)
                    current_id = v
                elif k == 'classification':
                    annotations[current_id] = v
                    current_id = None

    if current_id is not None and current_id not in annotations:
        print(f"Warning: annotation '{current_id}' has no classification",
              file=sys.stderr)

    return annotations


# --- Section splitting ---

def split_sections(text):
    """Split report text into sections by ### Section N: headers.

    Returns dict of section_number -> section_text.
    """
    sections = {}
    pattern = re.compile(r'^###\s+Section\s+(\d+):', re.MULTILINE)
    matches = list(pattern.finditer(text))

    for i, m in enumerate(matches):
        num = int(m.group(1))
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        sections[num] = text[start:end]

    return sections


# --- Header extraction ---

def extract_header(text):
    """Extract metadata from the report header."""
    header = {}

    # Extension name from title
    m = re.search(r'##\s+EGO Review Report\s*[—–-]\s*(.+)', text)
    if m:
        header['name'] = m.group(1).strip()

    # Verdict (may appear in header or Section 6)
    m = re.search(r'\*?\*?Verdict:?\*?\*?\s*:?\s*(NEEDS REVISION|LIKELY APPROVED|LIKELY REJECTED)',
                  text, re.IGNORECASE)
    if m:
        header['verdict'] = m.group(1).upper()

    # Lint summary
    m = re.search(
        r'\*?\*?ego-lint\*?\*?:\s*(\d+)\s*PASS,\s*(\d+)\s*FAIL,\s*(\d+)\s*WARN,\s*(\d+)\s*SKIP',
        text)
    if m:
        header['lint_summary'] = {
            'pass': int(m.group(1)),
            'fail': int(m.group(2)),
            'warn': int(m.group(3)),
            'skip': int(m.group(4)),
        }

    return header


# --- Finding extraction ---

SEVERITY_MAP = {'B': 'blocking', 'J': 'justification', 'A': 'advisory'}


def extract_file_line(text):
    """Extract file path and line from various formats."""
    # **File**: path:line or `path:line`
    m = re.search(r'\*\*File\*\*:\s*`?([^`\n:]+):(\d+(?:[-–]\d+)?)`?', text)
    if m:
        return m.group(1).strip(), m.group(2)

    # Inline backtick: `path:line`
    m = re.search(r'`([^`\n:]+\.\w+):(\d+(?:[-–]\d+)?)`', text)
    if m:
        return m.group(1).strip(), m.group(2)

    return None, None


def extract_description(text):
    """Extract the main description from a finding block."""
    # **What**: description
    m = re.search(r'\*\*What\*\*:\s*(.+?)(?=\n\*\*|\n####|\n---|\Z)', text, re.DOTALL)
    if m:
        return m.group(1).strip()

    # After backtick file ref: `file:line` — description
    m = re.search(r'`[^`]+`\s*[—–-]\s*(.+?)(?=\n\*\*|\n####|\n---|\Z)', text, re.DOTALL)
    if m:
        return m.group(1).strip()

    return None


def parse_findings_variant_b(section_text, severity_letter):
    """Parse findings in Variant B format: #### [B1] title (category)"""
    findings = []
    pattern = re.compile(
        r'####\s+\[(' + severity_letter + r'\d+)\]\s+(.+?)(?=\n)',
    )

    matches = list(pattern.finditer(section_text))
    for i, m in enumerate(matches):
        number = m.group(1)
        raw_title = m.group(2).strip()

        # Extract category from parenthetical suffix
        cat_m = re.search(r'\((\w[\w\s/,-]*)\)\s*$', raw_title)
        if cat_m:
            category = cat_m.group(1).strip().lower()
            title = raw_title[:cat_m.start()].strip()
        else:
            title = raw_title
            category = None

        # Get the block text for this finding
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(section_text)
        block = section_text[start:end]

        file_path, line = extract_file_line(block)
        description = extract_description(block)

        if not category:
            category = infer_category(title)

        finding_id = make_review_finding_id(title, category)

        findings.append({
            'id': finding_id,
            'severity': SEVERITY_MAP.get(severity_letter, 'unknown'),
            'number': number,
            'title': title,
            'category': category,
            'file': file_path,
            'line': line,
            'description': description,
            'section': {'B': 1, 'J': 2, 'A': 3}.get(severity_letter, 0),
        })

    return findings


def parse_findings_variant_a(section_text, severity_letter):
    """Parse findings in Variant A format: **B1. title**"""
    findings = []
    pattern = re.compile(
        r'\*\*(' + severity_letter + r'\d+)\.\s+(.+?)\*\*',
    )

    matches = list(pattern.finditer(section_text))
    for i, m in enumerate(matches):
        number = m.group(1)
        title = m.group(2).strip()

        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(section_text)
        block = section_text[start:end]

        file_path, line = extract_file_line(block)
        description = extract_description(block)
        category = infer_category(title)
        finding_id = make_review_finding_id(title, category)

        findings.append({
            'id': finding_id,
            'severity': SEVERITY_MAP.get(severity_letter, 'unknown'),
            'number': number,
            'title': title,
            'category': category,
            'file': file_path,
            'line': line,
            'description': description,
            'section': {'B': 1, 'J': 2, 'A': 3}.get(severity_letter, 0),
        })

    return findings


def parse_section_findings(section_text, severity_letter):
    """Parse findings from a section, trying both format variants."""
    # Try Variant B first (more structured, more common in recent runs)
    findings = parse_findings_variant_b(section_text, severity_letter)
    if findings:
        return findings

    # Fall back to Variant A
    return parse_findings_variant_a(section_text, severity_letter)


# --- Section 5: AI Pattern Analysis ---

def parse_ai_analysis(section_text):
    """Extract AI pattern analysis from Section 5."""
    result = {
        'provenance_score': None,
        'slop_assessment': None,
        'triggered_items': [],
    }

    # Provenance score
    m = re.search(r'\*?\*?Provenance Score\*?\*?:\s*(\d+|null|None)', section_text)
    if m:
        val = m.group(1)
        result['provenance_score'] = int(val) if val.isdigit() else None

    # AI Slop Assessment
    m = re.search(r'\*?\*?AI Slop Assessment\*?\*?:\s*\*?\*?(.+?)(?:\*\*)?(?:\n|$)',
                  section_text)
    if m:
        result['slop_assessment'] = m.group(1).strip().rstrip('*')

    # Triggered items
    m = re.search(r'\*?\*?Triggered items\*?\*?:\s*(.+?)(?:\n\n|\n\*\*|\Z)',
                  section_text, re.DOTALL)
    if m:
        items_text = m.group(1).strip()
        if items_text.lower() not in ('none', 'none.', 'n/a'):
            # Parse bullet list or comma-separated
            items = re.findall(r'[-*]\s+(.+)', items_text)
            if items:
                result['triggered_items'] = [i.strip() for i in items]
            elif items_text:
                result['triggered_items'] = [i.strip() for i in items_text.split(',')
                                             if i.strip()]

    return result


# --- Main parser ---

def parse_review(text, name=None, source_file=None):
    """Parse a .review.md report into structured data."""
    # Handle empty/truncated reports
    stripped = text.strip()
    if not stripped:
        return {
            'name': name or 'unknown',
            'timestamp': datetime.now(timezone.utc).isoformat(),
            'source_file': source_file,
            'truncated': True,
            'verdict': None,
            'sections_parsed': 0,
            'counts': {'blocking': 0, 'justification': 0, 'advisory': 0, 'total': 0},
            'findings': [],
            'ai_analysis': None,
            'lint_summary': None,
        }

    header = extract_header(text)
    sections = split_sections(text)

    if not name:
        name = header.get('name', 'unknown')

    # Check for truncated reports (no sections found)
    truncated = len(sections) < 6

    # Extract findings from sections 1-3
    findings = []
    section_map = {1: 'B', 2: 'J', 3: 'A'}
    for sec_num, letter in section_map.items():
        if sec_num in sections:
            findings.extend(parse_section_findings(sections[sec_num], letter))

    # Count by severity
    counts = {'blocking': 0, 'justification': 0, 'advisory': 0}
    for f in findings:
        sev = f['severity']
        if sev in counts:
            counts[sev] += 1
    counts['total'] = len(findings)

    # AI analysis from section 5
    ai_analysis = None
    if 5 in sections:
        ai_analysis = parse_ai_analysis(sections[5])

    # Verdict from header or section 6
    verdict = header.get('verdict')
    if not verdict and 6 in sections:
        m = re.search(
            r'(NEEDS REVISION|LIKELY APPROVED|LIKELY REJECTED)',
            sections[6], re.IGNORECASE)
        if m:
            verdict = m.group(1).upper()

    return {
        'name': name,
        'timestamp': datetime.now(timezone.utc).isoformat(),
        'source_file': source_file,
        'truncated': truncated,
        'verdict': verdict,
        'sections_parsed': len(sections),
        'counts': counts,
        'findings': findings,
        'ai_analysis': ai_analysis,
        'lint_summary': header.get('lint_summary'),
    }


def main():
    import argparse
    parser = argparse.ArgumentParser(
        description='Parse ego-review .review.md into structured JSON.')
    parser.add_argument('review_md', help='Path to .review.md file')
    parser.add_argument('--name', default=None, help='Extension name override')
    parser.add_argument('--annotations', default=None,
                        help='Annotation YAML for unclassified finding filtering')
    args = parser.parse_args()

    if not os.path.isfile(args.review_md):
        print(f"Error: file not found: {args.review_md}", file=sys.stderr)
        sys.exit(1)

    with open(args.review_md) as f:
        text = f.read()

    result = parse_review(text, name=args.name, source_file=args.review_md)

    # Filter unclassified findings against annotations
    if args.annotations:
        annotations = parse_annotations(args.annotations)
        result['unannotated_findings'] = [
            f for f in result['findings']
            if f['id'] not in annotations
        ]
    else:
        result['unannotated_findings'] = []

    json.dump(result, sys.stdout, indent=2)
    print()

    # Exit 2 when non-empty file produces zero sections (format mismatch)
    if text.strip() and result['sections_parsed'] == 0 and not result['truncated']:
        sys.exit(2)


if __name__ == '__main__':
    main()
